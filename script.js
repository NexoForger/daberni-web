function initHexGrid() {
    const canvas = document.getElementById('hexGridCanvas');
    if (!canvas) {
        return;
    }
    const context = canvas.getContext('2d');
    if (!context) {
        return;
    }

    if (window.innerWidth < 900 || window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
        canvas.style.display = 'none';
        return;
    }

    let width = 0;
    let height = 0;
    let cells = [];

    const size = 36;
    const hexWidth = Math.sqrt(3) * size;
    const hexRowHeight = size * 1.5;

    function buildGrid() {
        cells = [];
        const columns = Math.ceil(width / hexWidth) + 2;
        const rows = Math.ceil(height / hexRowHeight) + 2;

        for (let row = 0; row < rows; row += 1) {
            for (let column = 0; column < columns; column += 1) {
                cells.push({
                    x: column * hexWidth + (row % 2 ? hexWidth / 2 : 0),
                    y: row * hexRowHeight,
                    opacity: Math.random() * 0.14 + 0.02
                });
            }
        }
    }

    function resize() {
        width = canvas.width = window.innerWidth;
        height = canvas.height = window.innerHeight;
        buildGrid();
    }

    function drawHex(cell) {
        context.beginPath();
        for (let side = 0; side < 6; side += 1) {
            const angle = Math.PI / 3 * side + Math.PI / 6;
            const x = cell.x + size * Math.cos(angle);
            const y = cell.y + size * Math.sin(angle);
            if (side === 0) {
                context.moveTo(x, y);
            } else {
                context.lineTo(x, y);
            }
        }
        context.closePath();
        context.strokeStyle = `rgba(0, 184, 217, ${cell.opacity})`;
        context.lineWidth = 1;
        context.stroke();
    }

    function render() {
        context.clearRect(0, 0, width, height);
        cells.forEach((cell) => drawHex(cell));
    }

    function handleResize() {
        resize();
        render();
    }

    window.addEventListener('resize', handleResize);
    handleResize();
}

function initReveal() {
    const observer = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
            if (entry.isIntersecting) {
                entry.target.classList.add('is-visible');
                observer.unobserve(entry.target);
            }
        });
    }, { threshold: 0.14 });

    document.querySelectorAll('.reveal').forEach((element) => observer.observe(element));
}

function initServiceModal() {
    const modal = document.getElementById('serviceModal');
    if (!modal) {
        return;
    }

    const closeTargets = modal.querySelectorAll('[data-close-modal="true"]');
    let activeCard = null;

    document.addEventListener('click', (event) => {
        const card = event.target.closest('.service-card[data-service]');
        if (!card) {
            return;
        }
        activeCard = card;
        openServiceModal(card.dataset.service);
    });

    document.addEventListener('keydown', (event) => {
        const card = event.target.closest('.service-card[data-service]');
        if (card && (event.key === 'Enter' || event.key === ' ')) {
            event.preventDefault();
            activeCard = card;
            openServiceModal(card.dataset.service);
            return;
        }

        if (event.key === 'Escape' && modal.classList.contains('is-open')) {
            closeServiceModal();
        }
    });

    closeTargets.forEach((target) => {
        target.addEventListener('click', closeServiceModal);
    });

    function openServiceModal(serviceKey) {
        const language = document.documentElement.lang === 'ar' ? 'ar' : 'en';
        const content = serviceModalContent[language][serviceKey];
        if (!content) {
            return;
        }

        document.getElementById('serviceModalEyebrow').textContent = translations[language].modalEyebrow;
        document.getElementById('serviceModalTitle').textContent = content.title;
        document.getElementById('serviceModalOverview').textContent = content.overview;
        document.getElementById('serviceModalHowLabel').textContent = translations[language].modalHowLabel;
        document.getElementById('serviceModalExamplesLabel').textContent = translations[language].modalExamplesLabel;
        document.getElementById('serviceModalDetailsLabel').textContent = translations[language].modalDetailsLabel;

        fillList(document.getElementById('serviceModalSteps'), content.steps);
        fillList(document.getElementById('serviceModalExamples'), content.examples);
        fillChips(document.getElementById('serviceModalDetails'), content.details);

        const primaryArt = document.getElementById('serviceModalPrimaryArt');
        const secondaryArt = document.getElementById('serviceModalSecondaryArt');
        primaryArt.src = content.primaryArt;
        primaryArt.alt = `${content.title} illustration`;
        secondaryArt.src = content.secondaryArt;
        secondaryArt.alt = "";

        modal.classList.add('is-open');
        modal.setAttribute('aria-hidden', 'false');
        document.body.style.overflow = 'hidden';
    }

    function closeServiceModal() {
        modal.classList.remove('is-open');
        modal.setAttribute('aria-hidden', 'true');
        document.body.style.overflow = '';
        if (activeCard) {
            activeCard.focus();
        }
    }
}

function fillList(element, items) {
    element.innerHTML = '';
    items.forEach((item) => {
        const li = document.createElement('li');
        li.textContent = item;
        element.appendChild(li);
    });
}

function fillChips(element, items) {
    element.innerHTML = '';
    items.forEach((item) => {
        const chip = document.createElement('span');
        chip.textContent = item;
        element.appendChild(chip);
    });
}

function initLanguageToggle() {
    const button = document.getElementById('langToggle');
    const html = document.documentElement;

    applyTranslations('en');

    button.addEventListener('click', () => {
        const nextLang = html.lang === 'en' ? 'ar' : 'en';
        applyTranslations(nextLang);
    });
}

function applyTranslations(language) {
    const html = document.documentElement;
    const button = document.getElementById('langToggle');
    const dictionary = translations[language];

    html.lang = language;
    html.dir = language === 'ar' ? 'rtl' : 'ltr';
    button.textContent = language === 'en' ? 'العربية' : 'English';

    document.querySelectorAll('[data-i18n]').forEach((element) => {
        const key = element.dataset.i18n;
        if (dictionary[key]) {
            element.textContent = dictionary[key];
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
        const key = element.dataset.i18nPlaceholder;
        if (dictionary[key]) {
            element.setAttribute('placeholder', dictionary[key]);
        }
    });

    document.title = language === 'ar' ? 'دبّرني | Sort Me Out' : 'Daberni | Sort Me Out';
}

function initSubscribeForm() {
    const form = document.getElementById('subscribeForm');
    const status = document.getElementById('subscribeStatus');

    form.addEventListener('submit', async (event) => {
        event.preventDefault();
        setStatus(status, getMessage('subscribePending'), 'is-pending');

        try {
            const email = document.getElementById('subscribeEmail').value.trim();
            const response = await DataStore.addSubscriber({ email });

            if (response && response.reason === 'duplicate') {
                setStatus(status, getMessage('subscribeDuplicate'), 'is-error');
                return;
            }

            form.reset();
            setStatus(status, getMessage('subscribeSuccess'), 'is-success');
        } catch (error) {
            setStatus(status, error.message || getMessage('subscribeError'), 'is-error');
        }
    });
}

function initApplicationForm() {
    const form = document.getElementById('applicationForm');
    const status = document.getElementById('applicationStatus');

    form.addEventListener('submit', async (event) => {
        event.preventDefault();
        setStatus(status, getMessage('applicationPending'), 'is-pending');

        const fields = form.elements;

        const payload = {
            name: fields.name.value.trim(),
            phone: fields.phone.value.trim(),
            email: fields.email.value.trim(),
            city: fields.city.value.trim(),
            vehicleType: fields.vehicleType.value,
            vehicleYear: fields.vehicleYear.value.trim(),
            licenseNumber: fields.licenseNumber.value.trim(),
            yearsExperience: fields.yearsExperience.value,
            availability: fields.availability.value,
            platforms: Array.from(form.querySelectorAll('input[name="platforms"]:checked')).map((input) => input.value),
            additionalInfo: fields.additionalInfo.value.trim()
        };

        try {
            await DataStore.addApplication(payload);
            form.reset();
            setStatus(status, getMessage('applicationSuccess'), 'is-success');
        } catch (error) {
            setStatus(status, error.message || getMessage('applicationError'), 'is-error');
        }
    });
}

function initSuggestionForm() {
    const form = document.getElementById('suggestionForm');
    const status = document.getElementById('suggestionStatus');
    if (!form || !status) {
        return;
    }

    form.addEventListener('submit', (event) => {
        event.preventDefault();

        const fields = form.elements;
        const payload = {
            name: fields.suggestionName.value.trim(),
            suggestion: fields.suggestionText.value.trim(),
            submittedAt: new Date().toISOString()
        };

        try {
            const existing = JSON.parse(localStorage.getItem('daberniSuggestions') || '[]');
            existing.push(payload);
            localStorage.setItem('daberniSuggestions', JSON.stringify(existing));
            form.reset();
            setStatus(status, getMessage('suggestionSuccess'), 'is-success');
        } catch (error) {
            setStatus(status, getMessage('suggestionError'), 'is-error');
        }
    });
}

function setStatus(element, message, className) {
    element.textContent = message;
    element.className = `form-status ${className}`;
}

